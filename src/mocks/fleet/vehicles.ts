/**
 * Marcador do mapa. Quando o veículo está em uma viagem ativa, leva junto a
 * origem e o destino para que o mapa desenhe o trajeto.
 */
export function buildVehicleMarker(vehicle: Vehicle): MapVehicleMarker {
  const trip = TRIPS.find(
    (item) =>
      item.vehiclePlate === vehicle.plate &&
      (item.status === 'in_progress' || item.status === 'delayed'),
  );

  if (!trip) {
    return {
      id: vehicle.id,
      plate: vehicle.plate,
      status: vehicle.status,
      position: vehicle.lastPosition!,
    };
  }

  const road = roadRouteFor(trip.origin, trip.destination);

  return {
    id: vehicle.id,
    plate: vehicle.plate,
    status: vehicle.status,
    position: vehicle.lastPosition!,
    route: {
      origin: coordsForPlace(trip.origin),
      destination: coordsForPlace(trip.destination),
      ...(road ? { path: road.coordinates, distanceKm: road.distanceKm } : {}),
    },
  };
}
