let nudgeCount = 0;

/**
 * Posição simulada a partir da cidade. Veículos na mesma cidade recebem um
 * deslocamento pequeno e determinístico para não ficarem sobrepostos no mapa.
 */
function pos(city: string, state: string, x: number, y: number, speedKmh?: number): GeoPosition {
  const base = CITY_COORDS[city] ?? { lat: -15.7939, lng: -47.8828 };
  const nudge = nudgeCount++;
  return {
    lat: base.lat + (((nudge * 37) % 40) - 20) / 200,
    lng: base.lng + (((nudge * 53) % 40) - 20) / 200,
    city,
    state,
    x,
    y,
    speedKmh,
  };
}

function driver(id: string) {
  const d = DRIVERS.find((item) => item.id === id);
  return d ? { id: d.id, name: d.name } : undefined;
}

